import random

print(random.randint(5, 20))  # line 1
# the smallest number you will see is 5, the largest number you will see is 20
print(random.randrange(3, 10, 2))  # line 2
#the smallest number you will see is 3, the largest number is 9
# you won't see a 4 because it is even and it is counting in 2s in odd numbers
print(random.uniform(2.5, 5.5))  # line 3
# 2.5 and 5.5

print(random.randint(1, 100))
